/* student-scheme.js — the 12-week scheme of work for one subject. */

import { boot } from '../core/boot.js';
import { hydrateIcons, icon } from '../core/icons.js';
import { $, $$, esc, ring, humanMins } from '../core/ui.js';
import { url, param } from '../core/paths.js';
import { requireAuth } from '../core/auth.js';
import { mountShell } from '../components/shell.js';
import { getProgress } from '../data/progress.js';
import { byId, toneClass } from '../data/subjects.js';
import { schemeFor, nextTopic, hasRichLesson } from '../data/scheme.js';

boot();
const me = requireAuth('student');
function render() {
  const subject = byId(param('subject', 'maths')) || byId('maths');
  const p = getProgress();
  const weeks = schemeFor(subject.id, subject.name, p.doneTopics);
  const nxt = nextTopic(subject.id, subject.name, p.doneTopics);

  const totalTopics = weeks.reduce((a, w) => a + w.topics.length, 0);
  const doneTopics = weeks.reduce((a, w) => a + w.doneCount, 0);
  const pct = Math.round((doneTopics / totalTopics) * 100);
  const totalMins = weeks.reduce((a, w) => a + w.topics.reduce((b, t) => b + t.mins, 0), 0);

  const page = mountShell({
    user: me,
    active: 'subjects',
    title: `${subject.name} · Scheme of work`,
    subtitle: `${me.level || 'SS2'} · 12 weeks · generated by your AI teacher`,
  });

  page.innerHTML = `
    <a class="row gap-2 t-sm fw-semibold muted" href="${url('student/subjects.html')}"
       style="margin-bottom:var(--s-4)">
      ${icon('arrowL', 16)} All subjects
    </a>

    <!-- Subject header -->
    <section class="card card-pad-lg" style="margin-bottom:var(--s-6)">
      <div class="row between wrap gap-5">
        <div class="row gap-4" style="min-width:0">
          <span class="itile itile-lg ${toneClass(subject.tone)}" style="width:64px;height:64px;font-size:28px">
            ${subject.emoji}
          </span>
          <div style="min-width:0">
            <h1 style="font-size:var(--text-xl)">${esc(subject.name)}</h1>
            <p class="t-sm muted">${esc(subject.blurb)}</p>
            <div class="row gap-2 wrap" style="margin-top:var(--s-3)">
              <span class="chip chip-brand">${esc(me.level || 'SS2')}</span>
              <span class="chip">12 weeks</span>
              <span class="chip">${totalTopics} topics</span>
              <span class="chip">${humanMins(totalMins)} total</span>
            </div>
          </div>
        </div>

        <div class="row gap-5 items-center">
          ${ring(pct, {
            size: 92, stroke: 9,
            label: `<div><div class="fw-black">${pct}%</div><div class="t-2xs subtle">done</div></div>`,
          })}
          <div class="stack gap-2">
            ${nxt ? `
              <a class="btn btn-primary"
                 href="${url(`student/lesson.html?subject=${subject.id}&topic=${nxt.id}`)}">
                Continue ${icon('arrowR', 16)}
              </a>` : ''}
            <a class="btn btn-secondary"
               href="${url(`student/practice.html?subject=${subject.id}&mode=mock`)}">
              ${icon('trophy', 16)} Final exam
            </a>
          </div>
        </div>
      </div>
    </section>

    <!-- AI note -->
    <div class="alert alert-info" style="margin-bottom:var(--s-6)">
      ${icon('sparkle', 18)}
      <span>
        This scheme was built for <b>${esc(me.level || 'SS2')} ${esc(subject.name)}</b> from the
        WAEC and JAMB syllabus. Finish a week and the next unlocks — the final
        exam at week 12 pulls 40 questions from everything you covered.
      </span>
    </div>

    <!-- Weeks -->
    <section id="weeks">
      ${weeks.map((w, i) => {
        const locked = i > 0 && weeks[i - 1].doneCount === 0 && w.doneCount === 0 && i > 1;
        return `
        <article class="acc ${w.status === 'now' || (nxt && nxt.week === w.week) ? 'is-open' : ''} ${locked ? 'is-locked' : ''}"
                 data-week="${w.week}">
          <button class="acc-head">
            <span class="week-pill ${w.status === 'done' ? 'done' : w.status === 'now' ? 'now' : ''}">
              WK<br>${w.week}
            </span>
            <span class="grow" style="min-width:0">
              <span class="fw-bold clamp-1" style="display:block">${esc(w.title)}</span>
              <span class="hint">${w.doneCount}/${w.topics.length} topics ·
                ${w.topics.reduce((a, t) => a + t.mins, 0)} min</span>
            </span>
            <span class="hide-mobile" style="width:110px">
              <span class="bar bar-sm"><i style="width:${w.pct}%"></i></span>
            </span>
            <span class="caret">${icon('chevronR', 18)}</span>
          </button>

          <div class="acc-body">
            ${w.topics.map((t) => `
              <a class="topic-row" href="${url(`student/lesson.html?subject=${subject.id}&topic=${t.id}`)}">
                <span class="tick ${t.done ? 'on' : ''}">${t.done ? '✓' : ''}</span>
                <span class="grow" style="min-width:0">
                  <span class="t-sm fw-medium clamp-1" style="display:block">${esc(t.title)}</span>
                  <span class="hint">${t.mins} min read${hasRichLesson(`${subject.id}:${t.id}`) ? ' · full lesson' : ''}</span>
                </span>
                <span class="chip chip-outline">${t.done ? 'Revise' : 'Start'}</span>
              </a>`).join('')}

            ${w.week === 12 ? `
              <div class="alert alert-warn" style="margin-top:var(--s-3)">
                ${icon('trophy', 18)}
                <span>End of scheme: the AI sets a <b>40-question exam</b> with WAEC-style
                grading and feedback on every topic you missed.</span>
              </div>` : ''}
          </div>
        </article>`;
      }).join('')}
    </section>`;

  /* Accordion — one listener for all twelve weeks. */
  $$('.acc-head').forEach((head) => {
    head.addEventListener('click', () => head.closest('.acc').classList.toggle('is-open'));
  });

  hydrateIcons();
}

/* Start only once every module-level constant above is initialised.
   Calling render() higher up would hit the temporal dead zone on any
   const declared below it — a hoisted function can be called early,
   the constants it closes over cannot. */
if (me) render();
